/* 帮扶方案生成：规则化模板，非 AI 自由生成；同输入必同输出，可审计 */
(function () {
  var FOCUS = [
    {
      key: 'emotion', label: '情绪与心理支持',
      goal: '降低该生情绪低落的出现频次，建立可求助的表达渠道',
      actions: ['每周一次 15 分钟一对一谈心，固定时间地点；', '使用「情绪记录卡」让其自行记录，不做评判；', '超出教师能力范围时，转介学校心理教师或专业机构。']
    },
    {
      key: 'peer', label: '同伴关系与校园适应',
      goal: '减少孤立状态，建立至少 1 段稳定的同伴关系',
      actions: ['协商调整座位 / 安排同伴互助伙伴（须征求该生意见）；', '在班级活动中设置需要合作完成的任务，创造正向互动；', '与班主任商议班级氛围干预，及时制止起外号、排挤行为。']
    },
    {
      key: 'family', label: '家庭监护与亲子沟通',
      goal: '提升监护到位程度，恢复稳定的亲子联系',
      actions: ['与监护人约定固定通话时间与方式，写入计划书；', '每月至少 1 次家访或电话沟通，留存记录；', '向监护人说明监护责任与沟通方式，避免指责性表达。']
    },
    {
      key: 'study', label: '学业支持与在校表现',
      goal: '在 1 门学科上出现可观察的进步',
      actions: ['与该生共同确定「小步目标」（具体到每周可完成的事）；', '安排课后辅导或同伴助学，明确频次；', '与科任教师沟通阶段性降低要求、分层作业。']
    },
    {
      key: 'care', label: '生活照料与基本保障',
      goal: '基本生活照料得到稳定保障',
      actions: ['核实实际照料人与照料安排，形成书面记录；', '链接近亲属、村（居）委会提供日常支持；', '照料严重缺失时，按程序转介民政部门。']
    },
    {
      key: 'resource', label: '资源链接与政策帮扶',
      goal: '完成至少 1 项政策或社会资源的实际对接',
      actions: ['梳理可申请的资助与帮扶政策，列出清单；', '对接村（居）委会、民政、乡镇社工站，明确对接人；', '建立资源跟进表，记录申请进度与结果。']
    }
  ];

  var STAGES = [
    ['接案', '确认来源与初步观察，说明保密边界，取得学校与监护人知情同意。'],
    ['预估', '汇总家访与评估资料，界定问题与需求，判断风险等级。'],
    ['计划', '与服务对象共同确定目标与介入策略，形成本计划书。'],
    ['介入', '按本计划执行；每次介入后记录具体事实，不做主观定性。'],
    ['评估', '按「评估方式」每月复盘，比对基线，判断是否调整或结案。'],
    ['结案', '目标达成或需转介时结案，做交接与回访安排，完整留痕。']
  ];

  function line(n) { return '────────────────────────────────'; }
  function pad(s, n) { var out = s || '', i = out.length; while (i < n) { out += '　'; i++; } return out; }

  function build(c, a, opt) {
    var picks = FOCUS.filter(function (f) { return opt.focus.indexOf(f.key) >= 0; });
    if (!picks.length) picks = [FOCUS[0]];
    var L = [];

    L.push('个案服务计划书（模板）');
    L.push(line());
    L.push('');
    L.push('一、基本信息');
    L.push('  ' + pad('个案编号：', 10) + (c.id || '—'));
    L.push('  ' + pad('年级：', 10) + (c.grade || '—'));
    L.push('  ' + pad('当前阶段：', 10) + c.stage);
    L.push('  ' + pad('服务方法：', 10) + (opt.method === 'group' ? '小组工作' : '个案工作'));
    L.push('  ' + pad('计划周期：', 10) + opt.weeks + '　跟进频次：' + opt.freq);
    L.push('  ' + pad('负责人：', 10) + (opt.owner || '—'));
    L.push('  ' + pad('生成日期：', 10) + DB.today());
    L.push('  去标识化：本表请使用编号或「该生」，勿填写姓名、学号、家庭住址。');
    L.push('');

    L.push('二、问题预估（依据模块②评估结果）');
    L.push('  风险等级：' + a.level + '　总分：' + a.total + ' / 28　评估日期：' + a.date);
    L.push('  硬触发项：' + (a.hard.length ? a.hard.join('、') : '无'));
    L.push('  计分明细：');
    a.items.forEach(function (i) {
      L.push('    · ' + pad(i.label, 18) + pad(i.raw, 12) + i.score + ' / ' + i.max);
    });
    L.push('  初步观察：' + (c.note || '（待补充）'));
    L.push('');

    L.push('三、服务目标');
    L.push('  总目标：围绕' + picks.map(function (p) { return p.label; }).join('、') + '，在该生现有处境上形成可观察的改善，并保障其人身安全与基本照料。');
    picks.forEach(function (p, i) {
      L.push('  分目标' + (i + 1) + '（' + p.label + '）：' + p.goal + '。');
    });
    L.push('');

    L.push('四、介入策略');
    if (opt.method === 'group') {
      L.push('  小组名称：同伴支持成长小组');
      L.push('  对象与规模：同年级 / 同类需求学生 6–8 人（须逐人评估后确定）');
      L.push('  节次安排：4 节，' + opt.freq + '，每节 40 分钟');
      L.push('    第 1 节　认识彼此 · 建立小组契约');
      L.push('    第 2 节　我的优点与他人眼中的我');
      L.push('    第 3 节　合作任务 · 练习处理冲突');
      L.push('    第 4 节　回顾与告别 · 巩固支持网络');
      L.push('  小组工作之外的个别跟进仍按本计划「分目标」执行。');
    } else {
      L.push('  以个案工作为主：一对一会谈 + 家访 + 资源链接三线并行。');
      L.push('  会谈原则：开放式提问；客观事实与主观感受分开记录；不承诺做不到的事。');
    }
    L.push('');

    L.push('五、具体介入行动');
    picks.forEach(function (p) {
      L.push('  【' + p.label + '】' + p.goal);
      p.actions.forEach(function (act) { L.push('    · ' + act); });
    });
    L.push('');

    L.push('六、服务程序（六阶段）');
    STAGES.forEach(function (s) { L.push('  ' + pad(s[0], 6) + s[1]); });
    L.push('');

    L.push('七、频次与分工');
    L.push('  ' + pad('班主任 / 负责人：', 14) + opt.freq + '跟进，记录并更新台账。');
    L.push('  ' + pad('学校（德育处）：', 14) + '协调校内资源，监督支持事项落实。');
    L.push('  ' + pad('监护人：', 14) + '配合家访与约定事项。');
    L.push('  ' + pad('外部（按需）：', 14) + '乡镇社工站 / 民政 / 未保工作站 / 心理机构。');
    L.push('');

    L.push('八、成效评估方式');
    L.push('  · 基线：以本次评估总分 ' + a.total + ' 与各项得分为基线；');
    L.push('  · 过程：每次跟进记录一条具体行为事实（时间 + 做了什么 + 说了什么）；');
    L.push('  · 结果：' + opt.weeks + '后复评，比对总分与硬触发项是否消除；');
    L.push('  · 判断：风险下降且分目标达成 → 进入结案；风险持平或上升 → 调整重点或转介。');
    L.push('');

    L.push('九、风险提示与转介安排');
    if (a.hard.length) {
      L.push('  ⚠ 存在硬触发项（' + a.hard.join('、') + '）：常规流程已中断，先执行强制报告与人身安全处置，本计划仅作为后续跟进参考。');
      L.push('  1. 立即确保儿童人身安全，不要让其独处；');
      L.push('  2. 立即报告学校负责人，并按规定向公安、民政或卫生健康部门报告；');
      L.push('  3. 同步联系监护人；监护人失联或本人即为侵害人时，直接上报，不通过监护人转达；');
      L.push('  4. 记录时间、事实与处置过程，完整留痕。');
    } else if (a.level === '红') {
      L.push('  风险等级为红：在推进本计划的同时，同步转介属地社工站 / 未保工作站。');
    } else if (a.level === '黄') {
      L.push('  风险等级为黄：校内资源为主；连续两次复评风险上升即升级并考虑转介。');
    } else {
      L.push('  风险等级为绿：以班级层面关注为主，出现变化随时复评。');
    }
    L.push('');

    L.push('十、伦理声明');
    L.push('  本计划书由规则模板生成，仅为社工实务思路参考，不构成诊断或专业意见；');
    L.push('  是否启动计划、是否转介、如何处置，均由教师与学校依规决定；');
    L.push('  全程去标识化记录，不记录姓名、学号、身份证号、家庭住址。');

    return L.join('\n');
  }

  window.PLAN = { FOCUS: FOCUS, build: build };
})();
